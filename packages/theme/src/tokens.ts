// Pure token math for @sr/theme: merge scales, resolve theme role -> scale references, WCAG
// contrast, and the generated CSS text. No imports and erasable syntax only, so build.mjs can load
// it through Node type stripping.

/** A ramp maps a step to a raw value: the `soot` ramp maps "950" to "#0b0a09". */
export type Ramp = Readonly<Record<string, string>>;
/** Every ramp from scales/*.json, keyed by ramp name. */
export type Scales = Readonly<Record<string, Ramp>>;
/** A theme maps each role to a scale reference `<ramp>.<step>`, e.g. "surface-0": "soot.950". */
export type ThemeMap = Readonly<Record<string, string>>;

export interface ScaleFile {
  source: string;
  ramps: Scales;
}

export interface Merged {
  scales: Scales;
  problems: string[];
}

export interface Resolved {
  /** role -> raw value, in roles.json order. Only roles that resolved are present. */
  values: ReadonlyMap<string, string>;
  /** One line per defect, each naming the theme and the role or key at fault. */
  problems: string[];
}

/** Merges scale files into one ramp table. A ramp name defined twice is a problem. */
export function mergeScales(files: readonly ScaleFile[]): Merged {
  const owner = new Map<string, string>();
  const entries: [string, Ramp][] = [];
  const problems: string[] = [];
  for (const { source, ramps } of files) {
    for (const [name, ramp] of Object.entries(ramps)) {
      const first = owner.get(name);
      if (first !== undefined) {
        problems.push(`ramp "${name}" is defined in both ${first} and ${source}`);
        continue;
      }
      owner.set(name, source);
      entries.push([name, ramp]);
    }
  }
  return { scales: Object.fromEntries(entries), problems };
}

/** Resolves `<ramp>.<step>` against the scales; undefined if either part is missing. */
export function resolveRef(scales: Scales, ref: string): string | undefined {
  const dot = ref.indexOf(".");
  if (dot <= 0) return undefined;
  const rampName = ref.slice(0, dot);
  const step = ref.slice(dot + 1);
  if (!Object.hasOwn(scales, rampName)) return undefined;
  const ramp = scales[rampName];
  if (ramp === undefined || !Object.hasOwn(ramp, step)) return undefined;
  return ramp[step];
}

/**
 * Binds every role of the closed vocabulary through the theme. Reports roles the theme leaves
 * unbound, references that do not resolve, and theme keys that are not roles.
 */
export function resolveTheme(roles: readonly string[], scales: Scales, theme: ThemeMap, name: string): Resolved {
  const values = new Map<string, string>();
  const problems: string[] = [];
  for (const role of roles) {
    if (!Object.hasOwn(theme, role)) {
      problems.push(`${name}: role "${role}" is unbound`);
      continue;
    }
    const ref = theme[role] ?? "";
    const value = resolveRef(scales, ref);
    if (value === undefined) {
      problems.push(`${name}: role "${role}" -> "${ref}" does not resolve to a scale value`);
      continue;
    }
    values.set(role, value);
  }
  const known = new Set(roles);
  for (const key of Object.keys(theme)) {
    if (!known.has(key)) problems.push(`${name}: "${key}" is not a role in roles.json`);
  }
  return { values, problems };
}

/** The generated stylesheet for one theme: every resolved role as `--sr-<role>`. */
export function themeCss(name: string, values: ReadonlyMap<string, string>): string {
  const lines = [...values].map(([role, value]) => `  --sr-${role}: ${value};`);
  return [
    `/* Generated by packages/theme/build.mjs from roles.json and themes/${name}.json. Do not edit. */`,
    `[data-theme="${name}"] {`,
    ...lines,
    "}",
    "",
  ].join("\n");
}

export type Rgb = readonly [number, number, number];

/** Parses `#rrggbb` (any case) to 0-255 channels; undefined for anything else. */
export function parseHex(hex: string): Rgb | undefined {
  const m = /^#([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(hex);
  if (!m || m[1] === undefined || m[2] === undefined || m[3] === undefined) return undefined;
  return [parseInt(m[1], 16), parseInt(m[2], 16), parseInt(m[3], 16)];
}

const linear = (channel: number): number => {
  const c = channel / 255;
  return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
};

/** WCAG 2.x relative luminance of an sRGB colour, 0 (black) to 1 (white). */
export function relativeLuminance([r, g, b]: Rgb): number {
  return 0.2126 * linear(r) + 0.7152 * linear(g) + 0.0722 * linear(b);
}

/** WCAG 2.x contrast ratio, 1 (identical) to 21 (black on white). Order does not matter. */
export function contrastRatio(a: Rgb, b: Rgb): number {
  const la = relativeLuminance(a);
  const lb = relativeLuminance(b);
  return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05);
}
